#!/usr/bin/env python3
"""Seed entity markdown files.

Version numbers are deliberately absent: scripts/update-versions.mjs fills
currentVersion / releasedAt / eolAt / wikidata from Wikidata + endoflife.date
on a weekly schedule. Seeding them by hand would ship data that is wrong the
day it is written.
"""
import os
import textwrap

ROOT = "/home/claude/tuxly/content/entities"

def yml(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, list):
        return "[" + ", ".join(yml(x) for x in v) + "]"
    s = str(v)
    if any(c in s for c in ":#{}[]|>&*!%@`,") or s.strip() != s:
        return "'" + s.replace("'", "''") + "'"
    return s


def write(folder, slug, fields, body):
    lines = ["---"]
    for k, v in fields.items():
        if v is None or v == [] or v == "":
            continue
        lines.append(f"{k}: {yml(v)}")
    lines.append("---")
    lines.append("")
    lines.append(textwrap.dedent(body).strip())
    lines.append("")
    d = os.path.join(ROOT, folder)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, f"{slug}.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


